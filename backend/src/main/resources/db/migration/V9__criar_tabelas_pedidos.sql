-- ==============================================================================
-- Migration V9: Criação das tabelas de Pedidos e Itens de Pedido
-- ==============================================================================
-- Esta migration adiciona a persistência permanente das compras realizadas na farmácia.
-- Toda vez que um cliente inicia o checkout no Mercado Pago, um registro de 'pedido'
-- é criado com status 'PENDENTE'.
-- Quando o Mercado Pago aprova o pagamento via webhook (ou retorno), o status muda para 'PAGO'.
-- ==============================================================================

-- 1. Tabela mestre: PEDIDO
-- Guarda os dados gerais da compra, dados do comprador, endereço de entrega e valores calculados.
CREATE TABLE pedido (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  
  -- UUID único compartilhado com o Mercado Pago (external_reference)
  -- Permite conciliar o pagamento sem expor a chave primária sequencial do banco.
  referencia          VARCHAR(50)  NOT NULL UNIQUE,
  
  -- Vínculo opcional com a conta de usuário (se o cliente estiver logado na hora da compra)
  usuario_id          BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
  
  -- Dados do comprador congelados no momento da compra
  nome_comprador      VARCHAR(150) NOT NULL,
  email_comprador     VARCHAR(254) NOT NULL,
  cpf_comprador       VARCHAR(14)  NOT NULL,
  celular_comprador   VARCHAR(15)  NOT NULL,
  
  -- Tipo de entrega: 'entrega' (em domicílio) ou 'retirada' (na farmácia física)
  modo_entrega        VARCHAR(20)  NOT NULL,
  
  -- Endereço para entrega (nulos se modo_entrega = 'retirada')
  cep                 VARCHAR(9),
  rua                 VARCHAR(200),
  numero              VARCHAR(20),
  complemento         VARCHAR(100),
  bairro              VARCHAR(100),
  cidade              VARCHAR(100),
  uf                  VARCHAR(2),
  
  -- Detalhes financeiros
  cupom               VARCHAR(30),
  subtotal            NUMERIC(10, 2) NOT NULL,
  desconto            NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  frete               NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  total               NUMERIC(10, 2) NOT NULL,
  
  -- Status do pedido no ciclo de vida da farmácia
  -- PENDENTE: Aguardando pagamento no Mercado Pago
  -- PAGO: Pagamento aprovado e confirmado
  -- CANCELADO: Pagamento recusado, expirado ou cancelado pelo cliente
  -- FALHA: Erro no processamento
  status              VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
  
  -- Identificadores externos retornados pelo Mercado Pago
  mercado_pago_id     VARCHAR(100),
  mercado_pago_status VARCHAR(50),
  checkout_url        TEXT,
  
  -- Auditoria de datas com timezone (TIMESTAMPTZ)
  criado_em           TIMESTAMPTZ  NOT NULL DEFAULT now(),
  atualizado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  
  CONSTRAINT ck_pedido_status CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO', 'FALHA'))
);

-- Índices para buscas rápidas:
-- Por referência (usada nas telas de retorno do checkout e consultas de status)
CREATE INDEX idx_pedido_referencia ON pedido (referencia);
-- Por e-mail (usado para histórico de compras do cliente)
CREATE INDEX idx_pedido_email ON pedido (email_comprador);
-- Por status (usado pelo painel para filtrar pedidos pendentes ou pagos)
CREATE INDEX idx_pedido_status ON pedido (status);


-- 2. Tabela detalhe: ITEM_PEDIDO
-- Registra cada produto que compõe o pedido.
-- Os preços e nomes são duplicados aqui intencionalmente para garantir o princípio contábil:
-- se o produto mudar de preço no catálogo amanhã, o valor histórico deste pedido NÃO se altera.
CREATE TABLE item_pedido (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  
  -- Chave estrangeira ligando ao pedido pai; ao remover o pedido pai, remove os itens (CASCADE)
  pedido_id      BIGINT         NOT NULL REFERENCES pedido(id) ON DELETE CASCADE,
  
  -- Chave estrangeira opcional ao produto original
  produto_id     BIGINT         REFERENCES produto(id) ON DELETE SET NULL,
  
  -- Dados históricos congelados do produto
  nome_produto   VARCHAR(150)   NOT NULL,
  slug_produto   VARCHAR(100)   NOT NULL,
  quantidade     INT            NOT NULL,
  preco_unitario NUMERIC(10, 2) NOT NULL,
  total_item     NUMERIC(10, 2) NOT NULL,
  
  CONSTRAINT ck_item_quantidade CHECK (quantidade > 0)
);

CREATE INDEX idx_item_pedido_pedido ON item_pedido (pedido_id);
