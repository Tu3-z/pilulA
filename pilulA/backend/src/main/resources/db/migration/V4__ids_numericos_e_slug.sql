-- ==========================================================================
-- V4 · Chaves numéricas + slug.
--
-- Antes: a chave primária era o próprio código em texto ('dorflex-36').
-- Agora: cada tabela tem um id numérico gerado pelo banco (1, 2, 3…) para as
-- relações entre tabelas, e o código em texto vira a coluna "slug" (única),
-- usada nos links do site (produto.html?id=dorflex-36 continua funcionando).
--
-- Como trocar a chave de tabelas que já têm dados (e se referenciam):
--   1. cria as tabelas novas (nome_nova) com a estrutura nova;
--   2. copia os dados, trocando cada código pelo id novo (JOIN pelo slug);
--   3. apaga as tabelas antigas e renomeia as novas.
-- Tudo roda numa transação só: se algo falhar, nada muda.
-- SQL padrão: roda no PostgreSQL (Supabase) e no H2 dos testes.
-- ==========================================================================

-- 1. tabelas novas ----------------------------------------------------------

CREATE TABLE categoria_nova (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
  slug     VARCHAR(50)  NOT NULL,
  nome     VARCHAR(100) NOT NULL,
  rotulo   VARCHAR(100),
  arquivo  VARCHAR(100),
  tom      VARCHAR(20),
  ordem    INTEGER      NOT NULL DEFAULT 0,
  CONSTRAINT pk_categoria PRIMARY KEY (id),
  CONSTRAINT uk_categoria_slug UNIQUE (slug)
);

CREATE TABLE subcategoria_nova (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
  slug          VARCHAR(50)  NOT NULL,
  nome          VARCHAR(100) NOT NULL,
  categoria_id  BIGINT       NOT NULL,
  ordem         INTEGER      NOT NULL DEFAULT 0,
  CONSTRAINT pk_subcategoria PRIMARY KEY (id),
  CONSTRAINT uk_subcategoria_slug UNIQUE (slug),
  CONSTRAINT fk_subcategoria_categoria FOREIGN KEY (categoria_id) REFERENCES categoria_nova (id)
);

CREATE TABLE produto_nova (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
  slug             VARCHAR(80)   NOT NULL,
  nome             VARCHAR(150)  NOT NULL,
  marca            VARCHAR(100)  NOT NULL,
  sub              VARCHAR(100),
  selo             VARCHAR(30),
  descricao        VARCHAR(500),
  preco            NUMERIC(10,2) NOT NULL,
  preco_antigo     NUMERIC(10,2),
  receita          VARCHAR(20)   NOT NULL,
  destaque         BOOLEAN       NOT NULL DEFAULT FALSE,
  categoria_id     BIGINT        NOT NULL,
  subcategoria_id  BIGINT,
  forma            VARCHAR(20),
  rotulo           VARCHAR(40),
  foto             VARCHAR(255),
  ordem            INTEGER       NOT NULL DEFAULT 0,
  CONSTRAINT pk_produto PRIMARY KEY (id),
  CONSTRAINT uk_produto_slug UNIQUE (slug),
  CONSTRAINT ck_produto_preco CHECK (preco >= 0),
  CONSTRAINT ck_produto_preco_antigo CHECK (preco_antigo >= 0),
  CONSTRAINT ck_produto_receita CHECK (receita IN ('LIVRE', 'PRESCRICAO', 'RETENCAO')),
  CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria_nova (id),
  CONSTRAINT fk_produto_subcategoria FOREIGN KEY (subcategoria_id) REFERENCES subcategoria_nova (id)
);

-- 2. copia os dados (o id novo é gerado pelo banco, na ordem do menu) --------

INSERT INTO categoria_nova (slug, nome, rotulo, arquivo, tom, ordem)
SELECT id, nome, rotulo, arquivo, tom, ordem
FROM categoria
ORDER BY ordem;

INSERT INTO subcategoria_nova (slug, nome, categoria_id, ordem)
SELECT s.id, s.nome, c.id, s.ordem
FROM subcategoria s
JOIN categoria_nova c ON c.slug = s.categoria_id
ORDER BY c.ordem, s.ordem;

INSERT INTO produto_nova (slug, nome, marca, sub, selo, descricao, preco, preco_antigo, receita,
                          destaque, categoria_id, subcategoria_id, forma, rotulo, foto, ordem)
SELECT p.id, p.nome, p.marca, p.sub, p.selo, p.descricao, p.preco, p.preco_antigo, p.receita,
       p.destaque, c.id, s.id, p.forma, p.rotulo, p.foto, p.ordem
FROM produto p
JOIN categoria_nova c ON c.slug = p.categoria_id
LEFT JOIN subcategoria_nova s ON s.slug = p.subcategoria_id
ORDER BY p.ordem;

-- 3. troca as tabelas -------------------------------------------------------

DROP TABLE produto;
DROP TABLE subcategoria;
DROP TABLE categoria;

ALTER TABLE categoria_nova RENAME TO categoria;
ALTER TABLE subcategoria_nova RENAME TO subcategoria;
ALTER TABLE produto_nova RENAME TO produto;

CREATE INDEX idx_subcategoria_categoria ON subcategoria (categoria_id);
CREATE INDEX idx_produto_categoria ON produto (categoria_id);
CREATE INDEX idx_produto_subcategoria ON produto (subcategoria_id);
